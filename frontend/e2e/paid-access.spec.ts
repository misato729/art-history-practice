import {test,expect} from '@playwright/test'

test('paid navigation stays static, keeps two free exams and includes all eight exams',async({page,isMobile})=>{
 const requests:string[]=[]
 page.on('request',r=>{if(['/api/v1/exams','/api/v1/study_categories','/api/v1/questions/next'].includes(new URL(r.url()).pathname))requests.push(new URL(r.url()).pathname)})
 await page.goto('/')
 await expect(page.locator('.exam-card')).toHaveCount(8)
 await expect(page.locator('.exam-card').nth(1)).toHaveAttribute('href','/practice/2/1')
 await expect(page.locator('.exam-card').nth(2)).toHaveAttribute('href','/premium')
 for(const n of [6,7,8])await expect(page.locator('.exam-card').nth(n-1)).toHaveAttribute('href','/premium')
 if(isMobile)await page.getByRole('button',{name:'試験セットを開く',exact:true}).click()
 await page.getByRole('button',{name:'模擬試験2の問題一覧を開く',exact:true}).click()
 await expect(page.locator('#exam-2-questions a')).toHaveCount(85)
 await page.getByRole('button',{name:'模擬試験3の問題一覧を開く',exact:true}).click()
 await expect(page.locator('#exam-3-questions a')).toHaveCount(85)
 await expect(page.locator('#exam-3-questions a').first()).toHaveAttribute('href','/premium')
 expect(requests).toEqual([])
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})

test('the API and direct question route deny paid questions while free exam 2 still works',async({page})=>{
 await page.goto('/practice/2/1')
 await expect(page.getByRole('heading',{name:'問1',exact:true})).toBeVisible()
 const free=await page.request.get('/api/v1/questions/next?exam_number=2&question_number=1')
 expect(free.status()).toBe(200)
 for(const n of [3,4,5,6,7,8]){
  const denied=await page.request.get(`/api/v1/questions/next?exam_number=${n}&question_number=1`)
  expect(denied.status()).toBe(401)
  expect((await denied.json()).data).toBeUndefined()
 }
 await page.goto('/practice/3/1')
 await expect(page.getByRole('heading',{name:'模擬試験3はプレミアム会員向けです',exact:true})).toBeVisible()
 await expect(page.getByRole('radio')).toHaveCount(0)
 await page.goto('/premium')
 await expect(page.getByRole('heading',{name:'現在は販売準備中です',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:/Stripeで.*支払う/})).toHaveCount(0)
})

test('delayed initial authentication and catalog issue one valid question request and keep answer/next behavior',async({page})=>{
 const me:string[]=[],questions:string[]=[]
 page.on('request',r=>{const u=new URL(r.url());if(u.pathname==='/api/v1/me')me.push(u.pathname);if(u.pathname==='/api/v1/questions/next')questions.push(u.search)})
 await page.route('**/api/auth/get-session**',async route=>{const response=await route.fetch();await new Promise(done=>setTimeout(done,250));await route.fulfill({response})})
 await page.route('**/api/v1/exams',async route=>{await new Promise(done=>setTimeout(done,400));await route.continue()})
 await page.goto('/practice/1/1')
 await expect(page.getByRole('heading',{name:'問1',exact:true})).toBeVisible()
 expect(me).toHaveLength(1);expect(questions).toEqual(['?exam_number=1&question_number=1'])
 const {loadE2EFixture}=await import('../scripts/e2e-fixture.mjs');const fixture=loadE2EFixture();const correct=fixture.question.choices.findIndex((c:{is_correct:boolean})=>c.is_correct)
 await page.locator('.choices label').nth(correct).click();expect(questions).toHaveLength(1)
 await page.getByRole('button',{name:'回答する',exact:true}).click()
 await expect(page.getByText('正解です',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'次の問題',exact:true}).click()
 await expect(page.getByRole('heading',{name:'問2',exact:true})).toBeVisible()
 expect(questions).toEqual(['?exam_number=1&question_number=1','?exam_number=1&question_number=2'])
})

test('group start reuses its unfiltered catalog, and filtered starts do not populate the shared catalog',async({page})=>{
 const catalogs:string[]=[],questions:string[]=[]
 page.on('request',r=>{const u=new URL(r.url());if(u.pathname==='/api/v1/exams')catalogs.push(u.search);if(u.pathname==='/api/v1/questions/next')questions.push(u.search)})
 await page.goto('/practice/start?exams=1&group=1')
 await expect(page.getByRole('heading',{name:'問1',exact:true})).toBeVisible()
 expect(catalogs).toEqual(['']);expect(questions).toEqual(['?exam_number=1&question_number=1'])
 await page.route('**/api/v1/exams?**',route=>route.fulfill({json:{data:[]}}))
 catalogs.length=0;questions.length=0
 await page.goto('/practice/start?exams=1&study_category_codes=synthetic_filter')
 await expect(page.getByText('この条件に合う公開問題はまだありません。出題ジャンルや対象模擬試験を変更してください。',{exact:true})).toBeVisible()
 expect(catalogs).toEqual(['?study_category_codes=synthetic_filter']);expect(questions).toEqual([])
})

